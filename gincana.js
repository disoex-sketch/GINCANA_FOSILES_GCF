let claveActual = "";
let fosilActual = null;

function obtenerEstado() {
  try {
    const guardado = localStorage.getItem("gincana_fosiles_estado");
    return guardado ? JSON.parse(guardado) : {};
  } catch (e) {
    return {};
  }
}

function guardarEstado(estado) {
  try {
    localStorage.setItem("gincana_fosiles_estado", JSON.stringify(estado));
  } catch (e) {}
}

function actualizarMarcador() {
  const estado = obtenerEstado();
  const claves = Object.keys(datosFosiles);
  let contestadas = 0;
  let aciertos = 0;

  claves.forEach(clave => {
    if (estado[clave] !== undefined) {
      contestadas++;
      if (estado[clave].esCorrecto) aciertos++;
    }

    const btn = document.querySelector(`.btn-nav[data-id="${clave}"]`);
    if (btn) {
      btn.classList.remove("done-correct", "done-incorrect");
      if (estado[clave] !== undefined) {
        btn.classList.add(estado[clave].esCorrecto ? "done-correct" : "done-incorrect");
      }
    }
  });

  const elProgreso = document.getElementById("stat-progreso");
  const elAciertos = document.getElementById("stat-aciertos");
  const elNota = document.getElementById("stat-nota");

  if (elProgreso) elProgreso.innerText = `${contestadas} / ${claves.length}`;
  if (elAciertos) elAciertos.innerText = aciertos;
  if (elNota) {
    const porcentaje = contestadas > 0 ? Math.round((aciertos / contestadas) * 100) : 0;
    elNota.innerText = `${porcentaje}%`;
  }
}

function cargarFosil(clave) {
  const claves = Object.keys(datosFosiles);
  
  const mapaNumerico = {
    "1": "que", "2": "annularia", "3": "calamites", "4": "como","5": "cordaites", "6": "lepidodendron",
    "7": "paleontologo", "8": "polymorphopteris", "9": "sigillaria", "10": "historia"
  };

  if (mapaNumerico[clave]) clave = mapaNumerico[clave];
  if (!datosFosiles[clave]) clave = "que";
  
  const estado = obtenerEstado();

  claveActual = clave;
  fosilActual = datosFosiles[claveActual];

  const elImg = document.getElementById("img-fosil") || document.querySelector("img");
  if (elImg) {
    elImg.src = fosilActual.imagen;
    elImg.alt = claveActual;
  }

  const elTitulo = document.getElementById("titulo-fosil") || document.querySelector("h1, h2");
  if (elTitulo) elTitulo.innerText = fosilActual.titulo;

  const elPregunta = document.getElementById("pregunta-txt") || document.querySelector(".pregunta");
  if (elPregunta) elPregunta.innerText = fosilActual.pregunta;

 let contPista = document.getElementById("contenedor-pista");
  if (!contPista && elPregunta) {
    contPista = document.createElement("div");
    contPista.id = "contenedor-pista";
    contPista.style.margin = "15px 0";
    elPregunta.after(contPista);
  }

  if (contPista) {
    contPista.innerHTML = `
      <button id="btn-pista" type="button" onclick="mostrarPista()" style="background:#fff3cd; color:#856404; border:2px solid #ffeeba; padding:10px 16px; border-radius:8px; cursor:pointer; font-weight:bold; font-size: 1rem; width:100%; text-align:center;">💡 ¿Necesitas una pista?</button>
      <p id="texto-pista" style="display:none; background:#fff3cd; color:#856404; padding:12px; border-radius:8px; margin-top:8px; font-weight:500; line-height:1.4; border-left:4px solid #ffeeba; text-align:left;"></p>
    `;
    document.getElementById("texto-pista").innerText = fosilActual.pista;
  }

const contOpciones = document.getElementById("contenedor-opciones") || document.querySelector(".opciones");
  if (contOpciones) {
    contOpciones.innerHTML = "";
    fosilActual.opciones.forEach((opcion, index) => {
      const btn = document.createElement("button");
      btn.className = "btn-opt";
      btn.innerText = opcion;
      btn.onclick = () => responder(index);
      contOpciones.appendChild(btn);
    });
  }

  const respuestaPrevia = estado[claveActual];
  if (respuestaPrevia !== undefined) {
    mostrarResultado(respuestaPrevia.opcionElegida);
  } else {
    const elFb = document.getElementById("feedback");
    const elRes = document.getElementById("resena");
    if (elFb) elFb.style.display = "none";
    if (elRes) elRes.style.display = "none";
  }

  actualizarMarcador();
}

function mostrarPista() {
  const elBtnPista = document.getElementById("btn-pista");
  const elPistaTxt = document.getElementById("texto-pista");
  if (elBtnPista) elBtnPista.style.display = "none";
  if (elPistaTxt) elPistaTxt.style.display = "block";
}

function responder(index) {
  const estado = obtenerEstado();
  if (estado[claveActual] !== undefined) return;

  const esCorrecto = (index === fosilActual.correcta);
  estado[claveActual] = { opcionElegida: index, esCorrecto: esCorrecto };

  guardarEstado(estado);
  mostrarResultado(index);
  actualizarMarcador();
}

function mostrarResultado(indexElegido) {
  const fb = document.getElementById("feedback");
  const res = document.getElementById("resena");
  const btns = document.querySelectorAll(".btn-opt");

  btns.forEach((b, i) => {
    b.disabled = true;
    if (i === fosilActual.correcta) {
      b.style.borderColor = "var(--success, #28a745)";
      b.style.backgroundColor = "#d4edda";
    } else if (i === indexElegido) {
      b.style.borderColor = "var(--danger, #dc3545)";
      b.style.backgroundColor = "#f8d7da";
    }
  });

  if (fb) {
    if (indexElegido === fosilActual.correcta) {
      fb.className = "feedback correct";
      fb.innerText = "¡Correcto! Has acertado.";
    } else {
      fb.className = "feedback incorrect";
      fb.innerText = `¡Ocurrió un fallo! La respuesta correcta era: ${fosilActual.opciones[fosilActual.correcta]}`;
    }
    fb.style.display = "block";
  }

  const elResenaTxt = document.getElementById("resena-txt");
  if (elResenaTxt) elResenaTxt.innerText = fosilActual.resena;
  if (res) res.style.display = "block";
}

function reiniciarGincana() {
  if (confirm("¿Quieres borrar todo el progreso y empezar la gincana de cero?")) {
    localStorage.removeItem("gincana_fosiles_estado");
    
    window.location.href = window.location.pathname;
  }
}

document.addEventListener("DOMContentLoaded", () => {
  const params = new URLSearchParams(window.location.search);
  // Detecta si la URL trae ?fosil=nombre o ?id=nombre
  const idURL = params.get('fosil') || params.get('id');

  if (idURL && datosFosiles[idURL]) {
    cargarFosil(idURL);
  } else {

    const elTitulo = document.getElementById("titulo-fosil") || document.querySelector("h1, h2");
    if (elTitulo) elTitulo.innerText = "¡Bienvenido a La Gran Corta!";
    
    const elPregunta = document.getElementById("pregunta-txt") || document.querySelector(".pregunta");
    if (elPregunta) {
      elPregunta.innerText = "Por favor, escanea el código QR de cualquiera de las estaciones del recorrido para ver su pregunta.";
    }

    const elImg = document.getElementById("img-fosil") || document.querySelector("img");
    if (elImg) {
      elImg.style.display = "none";
    }

    const contOpciones = document.getElementById("contenedor-opciones") || document.querySelector(".opciones");
    if (contOpciones) contOpciones.innerHTML = "";
  }
});
